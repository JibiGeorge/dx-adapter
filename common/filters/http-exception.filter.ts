import {
  ArgumentsHost,
  Catch,
  ExceptionFilter,
  HttpException,
  HttpStatus,
  Logger,
} from '@nestjs/common';
import { Request, Response } from 'express';

@Catch()
export class HttpExceptionFilter implements ExceptionFilter {
  private readonly logger = new Logger(HttpExceptionFilter.name);

  catch(exception: any, host: ArgumentsHost) {
    const ctx = host.switchToHttp();
    const response = ctx.getResponse<Response>();
    const request = ctx.getRequest<Request>();

    let status = HttpStatus.INTERNAL_SERVER_ERROR;
    let errorCode = 'INTERNAL_SERVER_ERROR';
    let message = 'An unexpected error occurred';

    // If it's a direct HttpException (e.g. generated by BFF guards)
    if (exception instanceof HttpException) {
      status = exception.getStatus();
      const exceptionResponse = exception.getResponse();

      if (typeof exceptionResponse === 'string') {
        message = exceptionResponse;
        errorCode = this.statusToCode(status);
      } else if (typeof exceptionResponse === 'object' && exceptionResponse !== null) {
        const errorResponse = exceptionResponse as any;
        if (Array.isArray(errorResponse.message)) {
          message = errorResponse.message.join('; ');
        } else if (typeof errorResponse.message === 'string') {
          message = errorResponse.message;
        }
        errorCode = errorResponse.error?.toUpperCase().replace(/ /g, '_') ?? this.statusToCode(status);
      }
    } 
    // If it's an error forwarded from Core (it has success: false, error: {...})
    else if (exception?.success === false && exception?.error) {
      status = exception.statusCode || HttpStatus.BAD_REQUEST; // Try to extract status or default
      
      // Map common Core errors to HTTP status if possible based on errorCode
      if (exception.error.code === 'UNAUTHORIZED') status = HttpStatus.UNAUTHORIZED;
      else if (exception.error.code === 'NOT_FOUND') status = HttpStatus.NOT_FOUND;
      else if (exception.error.code === 'FORBIDDEN') status = HttpStatus.FORBIDDEN;

      errorCode = exception.error.code;
      message = exception.error.message;
    } else {
      this.logger.error('Unhandled exception', exception);
    }

    response.status(status).json({
      success: false,
      error: {
        code: errorCode,
        message,
      }
    });
  }

  private statusToCode(status: number): string {
    const map: Record<number, string> = {
      400: 'BAD_REQUEST',
      401: 'UNAUTHORIZED',
      403: 'FORBIDDEN',
      404: 'NOT_FOUND',
      409: 'CONFLICT',
      422: 'UNPROCESSABLE_ENTITY',
      429: 'TOO_MANY_REQUESTS',
      500: 'INTERNAL_SERVER_ERROR',
    };
    return map[status] ?? 'ERROR';
  }
}
